#!/usr/bin/env python3
"""Compiles src/render/shaders/quad.hlsl for every GPU backend and writes the embedded headers
in src/render/shaders/gen/.

Steps (each runs when its tool is found; the others keep the committed output):

  spirv    glslang (HLSL front end) -> SPIR-V 1.0, validated with spirv-val  -> quad_spirv.h
  dxbc     fxc.exe /T vs_4_0, ps_4_0 /O3 (Windows SDK)                       -> quad_dxbc.h
  metal    xcrun metal -std=macos-metal2.3 -mmacosx-version-min=13.0 on
           gen/quad.metal, then xcrun metallib                               -> quad_metallib.h
  msl      (only with --msl-from-spirv) SPIRV-Cross --msl 2.3 rewrites gen/quad.metal from the
           SPIR-V. Without it gen/quad.metal is the committed translation of quad.hlsl.

Usage:
  python3 tools/gen_shaders.py [--only spirv,dxbc,metal] [--check] [--require]
                               [--fxc PATH] [--glslang PATH] [--import-dxbc DIR]

  --check        compare instead of writing; exit 1 when a generated header differs (CI).
  --require      fail when a selected step has no tool (KT_SHADER_TOOLS=required).
  --import-dxbc  take quad.vs.dxbc / quad.ps.dxbc compiled on a Windows host.

Tool versions used for the committed outputs are listed in src/render/shaders/README.txt.
"""
import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "render", "shaders", "quad.hlsl")
GEN = os.path.join(ROOT, "src", "render", "shaders", "gen")


def run(cmd):
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if r.returncode != 0:
        sys.stderr.write(" ".join(cmd) + "\n" + r.stdout)
        raise SystemExit(f"gen_shaders: {os.path.basename(cmd[0])} failed")
    return r.stdout


def header(guard_name, arrays, align):
    """C++ header with one constexpr byte array per (name, bytes) and a content hash."""
    h = hashlib.sha256()
    for _, data in arrays:
        h.update(data)
    out = [
        "// GENERATED by tools/gen_shaders.py from src/render/shaders/quad.hlsl. Do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace kt::render::shaders {",
        "",
        f'inline constexpr const char k{guard_name}Hash[] = "sha256:{h.hexdigest()[:16]}";',
    ]
    for name, data in arrays:
        out.append("")
        out.append(f"alignas({align}) inline constexpr unsigned char {name}[] = {{")
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        out.append("};")
    out += ["", "}  // namespace kt::render::shaders", ""]
    return "\n".join(out)


def emit(path, text, check, changed):
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old == text:
        print(f"unchanged {os.path.relpath(path, ROOT)}")
        return
    if check:
        changed.append(path)
        print(f"DIFFERS   {os.path.relpath(path, ROOT)}")
        return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote     {os.path.relpath(path, ROOT)}")


def find(tool, explicit=None):
    if explicit:
        return explicit
    return shutil.which(tool)


def find_fxc():
    p = shutil.which("fxc") or shutil.which("fxc.exe")
    if p:
        return p
    kits = r"C:\Program Files (x86)\Windows Kits\10\bin"
    if os.path.isdir(kits):
        for v in sorted(os.listdir(kits), reverse=True):
            c = os.path.join(kits, v, "x64", "fxc.exe")
            if os.path.exists(c):
                return c
    return None


# glslang version that produced the committed SPIR-V (README.txt). Other versions emit different
# bytes (generator word, instruction order) for the same source, so --check compares only with it.
GLSLANG_PINNED = "16.6.0"


def glslang_version(glslang):
    text = subprocess.run([glslang, "--version"], capture_output=True, text=True).stdout
    m = re.search(r"Glslang Version:\s*\d+:(\d+\.\d+\.\d+)", text)
    return m.group(1) if m else None


def step_spirv(tmp, args):
    glslang = find("glslangValidator", args.glslang) or find("glslang")
    if not glslang:
        return None
    if args.check:
        version = glslang_version(glslang)
        if version != GLSLANG_PINNED:
            print(f"skipped   spirv check (glslang {version}, outputs pinned to {GLSLANG_PINNED})")
            return "version"
    out = {}
    for stage, entry, name in (("vert", "vs_main", "vs"), ("frag", "ps_main", "ps")):
        spv = os.path.join(tmp, f"quad.{name}.spv")
        # t0 moves to binding 1 so that the constant buffer (b0) keeps binding 0 in one set.
        run([glslang, "-D", "-V", "--target-env", "vulkan1.0", "-S", stage, "-e", entry,
             "--shift-texture-binding", "1", "-o", spv, SRC])
        val = find("spirv-val")
        if val:
            run([val, "--target-env", "vulkan1.0", spv])
        elif args.require:
            raise SystemExit("gen_shaders: spirv-val not found")
        out[name] = open(spv, "rb").read()
    return out


def step_dxbc(tmp, args):
    if args.import_dxbc:
        return {n: open(os.path.join(args.import_dxbc, f"quad.{n}.dxbc"), "rb").read() for n in ("vs", "ps")}
    fxc = args.fxc or find_fxc()
    if not fxc:
        return None
    out = {}
    for profile, entry, name in (("vs_4_0", "vs_main", "vs"), ("ps_4_0", "ps_main", "ps")):
        obj = os.path.join(tmp, f"quad.{name}.dxbc")
        run([fxc, "/nologo", "/T", profile, "/E", entry, "/O3", "/Qstrip_reflect", "/Qstrip_debug",
             "/Fo", obj, SRC])
        out[name] = open(obj, "rb").read()
    return out


def step_msl(tmp, spirv, args):
    cross = find("spirv-cross")
    if not cross or not spirv:
        return False
    parts = []
    for name in ("vs", "ps"):
        spv = os.path.join(tmp, f"quad.{name}.nodshift.spv")
        stage, entry = ("vert", "vs_main") if name == "vs" else ("frag", "ps_main")
        glslang = find("glslangValidator", args.glslang) or find("glslang")
        run([glslang, "-D", "-V", "--target-env", "vulkan1.0", "-S", stage, "-e", entry, "-o", spv, SRC])
        parts.append(run([cross, "--msl", "--msl-version", "20300", "--msl-decoration-binding", spv]))
    text = ("// GENERATED by tools/gen_shaders.py (SPIRV-Cross) from src/render/shaders/quad.hlsl.\n"
            + "\n".join(parts))
    with open(os.path.join(GEN, "quad.metal"), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return True


def step_metal(tmp):
    if sys.platform != "darwin" or not shutil.which("xcrun"):
        return None
    try:
        subprocess.run(["xcrun", "-f", "metal"], check=True, capture_output=True)
    except subprocess.CalledProcessError:
        return None
    air = os.path.join(tmp, "quad.air")
    lib = os.path.join(tmp, "quad.metallib")
    run(["xcrun", "-sdk", "macosx", "metal", "-std=macos-metal2.3", "-mmacosx-version-min=13.0",
         "-fno-fast-math", "-c", os.path.join(GEN, "quad.metal"), "-o", air])
    run(["xcrun", "-sdk", "macosx", "metallib", air, "-o", lib])
    return open(lib, "rb").read()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="spirv,dxbc,metal")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--require", action="store_true")
    ap.add_argument("--fxc")
    ap.add_argument("--glslang")
    ap.add_argument("--import-dxbc")
    ap.add_argument("--msl-from-spirv", action="store_true")
    args = ap.parse_args()
    steps = set(args.only.split(","))
    changed = []
    os.makedirs(GEN, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        spirv = None
        if "spirv" in steps or args.msl_from_spirv:
            spirv = step_spirv(tmp, args)
            if spirv is None:
                print("skipped   spirv (glslang not found)")
                if args.require:
                    return 1
            elif spirv == "version":
                spirv = None
            elif "spirv" in steps:
                emit(os.path.join(GEN, "quad_spirv.h"),
                     header("QuadSpirv", [("kQuadVsSpirv", spirv["vs"]), ("kQuadPsSpirv", spirv["ps"])], 4),
                     args.check, changed)
        if args.msl_from_spirv and not step_msl(tmp, spirv, args):
            print("skipped   msl (spirv-cross not found)")
        if "dxbc" in steps:
            dxbc = step_dxbc(tmp, args)
            if dxbc is None:
                print("skipped   dxbc (fxc not found)")
                if args.require and sys.platform == "win32":
                    return 1
            else:
                emit(os.path.join(GEN, "quad_dxbc.h"),
                     header("QuadDxbc", [("kQuadVsDxbc", dxbc["vs"]), ("kQuadPsDxbc", dxbc["ps"])], 4),
                     args.check, changed)
        if "metal" in steps:
            lib = step_metal(tmp)
            if lib is None:
                print("skipped   metal (no Metal toolchain)")
                if args.require and sys.platform == "darwin":
                    return 1
            else:
                emit(os.path.join(GEN, "quad_metallib.h"), header("QuadMetallib", [("kQuadMetallib", lib)], 4),
                     args.check, changed)
    return 1 if changed else 0


if __name__ == "__main__":
    sys.exit(main())
