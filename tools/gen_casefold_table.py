#!/usr/bin/env python3
"""Generate src/store/casefold_table.inc, the simple case folding of the history store.

Input is CaseFolding.txt of the Unicode Character Database. Only the C (common) and S
(simple) mappings are used: one code point maps to one code point, so folding works per
scalar on the write path.

Usage:
    gen_casefold_table.py --ucd DIR [--out FILE]
    gen_casefold_table.py --fetch 16.0.0 --ucd DIR [--out FILE]   # download first

Stdlib only. The output is a sorted list of runs {first, last, delta, step}: code points
first, first+step, ..., last map to cp + delta. step is 1 (blocks such as Cyrillic) or 2
(alternating upper/lower pairs such as Latin Extended-A).
"""

import argparse
import os
import urllib.request


def parse(path):
    m = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            code, status, mapping = [x.strip() for x in line.split(";")[:3]]
            if status not in ("C", "S"):
                continue
            m[int(code, 16)] = int(mapping, 16)
    return m


def runs(m):
    out = []
    for cp in sorted(m):
        delta = m[cp] - cp
        if out:
            first, last, d, step = out[-1]
            if d == delta and step in (0, cp - last) and cp - last in (1, 2):
                out[-1] = (first, cp, d, cp - last)
                continue
        out.append((cp, cp, delta, 0))
    return [(a, b, d, s or 1) for a, b, d, s in out]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucd", required=True)
    ap.add_argument("--fetch")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "src", "store",
                                                  "casefold_table.inc"))
    a = ap.parse_args()
    path = os.path.join(a.ucd, "CaseFolding.txt")
    if a.fetch:
        os.makedirs(a.ucd, exist_ok=True)
        url = f"https://www.unicode.org/Public/{a.fetch}/ucd/CaseFolding.txt"
        urllib.request.urlretrieve(url, path)
    version = "?"
    with open(path, encoding="utf-8") as f:
        first = f.readline()
        if first.startswith("# CaseFolding-"):
            version = first[len("# CaseFolding-"):].split(".txt")[0]
    r = runs(parse(path))
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_casefold_table.py. Do not edit.\n")
        f.write(f"// Unicode {version}: CaseFolding.txt, statuses C and S; {len(r)} runs.\n")
        f.write("// {first, last, delta, step}\n")
        for first, last, d, step in r:
            f.write(f"{{0x{first:X}, 0x{last:X}, {d}, {step}}},\n")


if __name__ == "__main__":
    main()
