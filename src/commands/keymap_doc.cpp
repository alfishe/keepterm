namespace kt::commands {

namespace {

constexpr Ctx kNarrowing = Ctx::Palette | Ctx::FindBar | Ctx::CopyMode | Ctx::Sidebar | Ctx::TextInput;

std::string cell(const Keymap& km, const Command& c, bool with_args) {
    std::string out;
    for (const Binding* b : km.bindings_for(c.id)) {
        if (b->args.empty() == with_args) continue;
        if (!out.empty()) out += ", ";
        out += "`" + format_sequence(b->seq, km.os(), Format::Config) + "`";
        const Ctx narrowed = b->when & kNarrowing;
        if (any(narrowed)) out += " (" + format_ctx(narrowed) + ")";
        if (b->global) out += " (global)";
    }
    return out.empty() ? "—" : out;
}

std::string escape_pipes(std::string_view s) {
    std::string out;
    for (const char ch : s) {
        if (ch == '|') out += "\\|";
        else out += ch;
    }
    return out;
}

}  // namespace

std::string generate_keymap_markdown(const CommandRegistry& r) {
    const Keymap mac = Keymap::defaults_for(Os::MacOS, r);
    const Keymap win = Keymap::defaults_for(Os::Windows, r);
    const Keymap lin = Keymap::defaults_for(Os::Linux, r);
    std::string out;
    out += "# Default keymap\n\n";
    out += "<!-- Generated by `keepterm --command keymap`; do not edit. A unit test checks that it is current. -->\n\n";
    out += "Every command of keepterm with its default chords on each OS. Chords are written in "
           "the `[keys]` grammar of `config.toml`: `cmd` and `opt` are macOS Command and Option; `primary` (not "
           "used below) is `cmd` on macOS and `ctrl+shift` elsewhere. A chord sequence is written with spaces "
           "(`ctrl+k ctrl+s`). Change a binding with `[keys]`, for example `\"pane.split_right\" = \"ctrl+shift+e\"`, "
           "or remove it with `\"none\"`. — means no default chord; the command is still in the palette and "
           "in `keepterm --command run`.\n\n";
    out += "Contexts in parentheses narrow where a chord works (`find_bar`: while the find bar has focus). "
           "Hidden commands (palette navigation, sidebar keys) work only in their context and are not listed in "
           "the palette.\n";
    Category current = Category::App;
    bool first = true;
    for (const Command& c : r.all()) {
        if (!c.bindable) continue;
        if (first || c.category != current) {
            current = c.category;
            first = false;
            out += "\n## ";
            out += category_title(c.category);
            out += "\n\n| Command | Id | macOS | Windows | Linux |\n|---|---|---|---|---|\n";
        }
        std::string title = escape_pipes(c.title);
        if (!c.palette_visible) title += " *(hidden)*";
        const bool args = c.id == "tab.select";
        auto col = [&](const Keymap& km) {
            if (!args) return escape_pipes(cell(km, c, false));
            const auto bs = km.bindings_for(c.id);
            if (bs.size() < 2) return escape_pipes(cell(km, c, true));
            return "`" + format_sequence(bs.front()->seq, km.os(), Format::Config) + "` \u2026 `" +
                   format_sequence(bs.back()->seq, km.os(), Format::Config) + "`";
        };
        out += "| " + title + " | `" + std::string(c.id) + "` | " + col(mac) + " | " + col(win) + " | " + col(lin) +
               " |\n";
    }
    out += "\nTab selection: holding the modifier and typing more digits within a second addresses tabs past 9 "
           "(`cmd+1` `cmd+2` selects tab 12 when there are 12 or more).\n";
    return out;
}

}  // namespace kt::commands
